    /// The tree decomposition round-trips through the TOML vocabulary: what
    /// tree_leaves emits is exactly what a hand-authored [[tab.panes]] list
    /// would say for the same tree.
    #[test]
    fn tree_leaves_matches_toml_pane_list() {
        let tree = split("down", 0.5, pane(Some("x")), split("right", 0.3, pane(Some("y")), pane(Some("z"))));
        let mut out = Vec::new();
        tree_leaves(&tree, None, &mut out);
        let x: Vec<Option<(String, f64)>> = out.iter().map(|(_, s)| s.clone()).collect();
        assert_eq!(x[0], None);
        assert_eq!(x[1], Some(("down".to_string(), 0.5)));
        assert_eq!(x[2], Some(("right".to_string(), 0.3)));
    }
