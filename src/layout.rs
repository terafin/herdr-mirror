// TOML workspace layout: capture, persist, and re-assert the shared mirror
// workspace's shape.
//
// This is the "a TOML that represents the workspace layout, saved and
// customizable across reboot" contract. The file (`layout.toml`, stored
// beside the per-host state, NOT beside hosts.toml — that file stays the host
// contract) is a hand-editable description of the fleet's local gang
// workspace: its label and its tabs in order, each tab listing its panes
// (which host a leaf mirrors; a hand-authored layout can also add split
// directions, following herdr-plus's `[[tabs.panes]]` vocabulary).
//
// What the file DOES and DOESN'T control, honestly:
//   - DOES: which workspace the mirrors share (label restamp), which tabs
//     exist in what order (native `tab.move`), and a readable leaf→host map.
//   - DOESN'T: intra-tab split geometry in the live arrangement. Converge
//     keeps the mirror tabs' topology faithful to the remote (layout_sync +
//     `layout.set_split_ratio`) and herdr cannot re-parent panes across tabs
//     after creation (`pane.move` returns SameTab), so `apply` re-orders and
//     never force-splits a live mirror. Split direction/ratio are captured
//     into the file for reference and future edits.
//
// Nothing here ever writes to a REMOTE herdr: the file shapes the local gang
// workspace only, so re-applying it can never rename a bot's workspaces.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::api::ApiClient;
